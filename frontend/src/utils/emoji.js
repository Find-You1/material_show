const RECENT_KEY = 'lumen.emoji.recent'
const RECENT_MAX = 16

export function loadRecentEmojis() {
  try {
    const raw = localStorage.getItem(RECENT_KEY)
    const list = raw ? JSON.parse(raw) : []
    return Array.isArray(list) ? list.filter((e) => typeof e === 'string').slice(0, RECENT_MAX) : []
  } catch {
    return []
  }
}

export function rememberEmoji(emoji) {
  const next = [emoji, ...loadRecentEmojis().filter((e) => e !== emoji)].slice(0, RECENT_MAX)
  try {
    localStorage.setItem(RECENT_KEY, JSON.stringify(next))
  } catch {
    // 隐私模式写不进去就只影响「最近使用」，不阻断发消息
  }
  return next
}
